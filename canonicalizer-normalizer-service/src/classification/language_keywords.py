def get_keywords_for_language(language_code: str, domain: str) -> list[str]:
    """Get keywords for a specific language and domain.

    Args:
        language_code: ISO 639-1 language code
        domain: Domain category

    Returns:
        List of keywords for the domain in the specified language
    """
    language_dict = LANGUAGE_KEYWORDS.get(language_code, {})
    return language_dict.get(domain, [])


def get_all_keywords_for_language(language_code: str) -> dict[str, list[str]]:
    """Get all keywords for a specific language.

    Args:
        language_code: ISO 639-1 language code

    Returns:
        Dictionary mapping domains to keywords
    """
    return LANGUAGE_KEYWORDS.get(language_code, {})

